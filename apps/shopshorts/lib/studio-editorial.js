export function storyArcGuide(brief) {
  return `킬링파트 설계: ${PAYOFF_GUIDES[brief.category]}
핵심 메시지를 정한 다음, 가장 기억에 남을 구체적인 대사·장면 하나를 먼저 설계하고 도입과 결말을 연결하세요.
1. 도입(hook): 첫 장면의 실제 내레이션·대사에서 시청자가 답을 알고 싶어질 구체적인 질문·갈등·상황을 여세요. 인사나 주제 소개로 시간을 쓰거나 '끝까지 보세요' 같은 빈 약속을 하지 마세요.
2. 킬링파트(payoff): 도입에서 심은 질문·단서를 회수하며 이해나 상황이 달라지는 순간을 만드세요. 내레이션 안에 기억할 핵심 대사를 쓰고, 그 대사가 성립하는 앞뒤 맥락과 구체적 행동·화면을 붙이세요. 직전까지의 해석·예상과 무엇이 어떻게 달라지는지 대사 자체에서 알아들을 수 있어야 합니다. 다른 주제에도 그대로 붙일 수 있는 표어 하나로 때우지 마세요.
킬링파트 후보로 서로 다른 관점 전환·구체적인 대비·단서 회수를 검토하고 주제에 가장 잘 맞는 하나를 선택하세요. 앞에서 이미 말한 교훈의 반복이나 예상대로 좋은 말을 하는 장면에 payoff 이름만 붙이지 마세요. 도입의 한 단어·사물·행동을 다시 등장시켜 의미가 달라지게 하거나, 질문·선택이 바뀌는 정확한 순간을 만드세요. 후보 목록이나 검토 과정은 반환하지 마세요.
3. 마무리(ending): 마지막 장면에서 그 발견으로 달라지는 구체적인 말·행동·선택을 보여주세요. 도입의 약속은 이번 영상 안에서 회수하고, 설명형 콘텐츠의 답을 다음 편으로 미루지 마세요.
${brief.format === 'long' ? '롱폼은 초반에 작은 답을 먼저 주고 본문에서 근거·예시를 쌓아 핵심 킬링파트로 발전시키세요. 끝까지 답을 숨기거나 반전을 반복하지 마세요.' : '숏폼은 중심 킬링파트 하나에 집중하세요. 긴장이나 감탄사를 반복하지 말고 도입·맥락·발견·실천에 시간을 배분하세요.'}
사용자가 정한 주제·길이·분위기는 유지하세요. 공포·수치심·죄책감을 부추기거나 사실을 과장해 주목을 끌지 마세요. 자막·음악·카메라 지시만으로 킬링파트를 대신하지 마세요.
자체 검토: 킬링파트를 빼면 도입의 질문이 풀리지 않거나 결말의 의미가 달라지는가? 그렇지 않으면 단순 요약이므로 다시 설계하세요. 자연스러운 대본 안에 녹이고 '훅', '킬링파트'라는 제작 용어를 읽게 하지 마세요.`;
}
