export function musicUnits(language: StudyLanguage): Unit[] {
  if (language !== "ja") return [];
  return musicLessons.map((lesson, i) => ({
    id: `music:ja:pretender:${i + 1}`,
    language,
    scene: "music",
    level: i + 1,
    title: lesson.title,
    phrase: lesson.steps[0].phrase,
    source: "music",
  }));
}
export function musicLesson(unit: Unit): MusicLesson | undefined {
  if (unit.source !== "music" || unit.language !== "ja" ||
      unit.id !== `music:ja:pretender:${unit.level}`) return undefined;
  return musicLessons[unit.level - 1];
}
