type MusicLesson = {
  title: string;
  goal: string;
  listen: string;
  pattern: string;
  steps: { cue: string; phrase: Phrase }[];
};
// Original speaking exercises, not lyrics, translations or phonetic copies of the song.
// Each row is cue | Japanese | Korean pronunciation aid | Korean meaning.
function steps(rows: string): MusicLesson["steps"] {
  return rows.trim().split("\n").map((row) => {
    const [cue, text, reading, meaning] = row.split("|");
    return { cue, phrase: { text, reading, meaning } };
  });
}
